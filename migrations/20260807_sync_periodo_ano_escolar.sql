-- ============================================================
-- 20260807_sync_periodo_ano_escolar.sql
-- Sincroniza Periodo Escolar <-> Año Escolar
-- ("Sin periodo activo" en Calificaciones aunque el periodo
--  aparece como "Activo" en Períodos del Año Escolar).
--
-- Causas raíz que corrige:
--   1. Ningún año escolar tenía is_current = true (o estaba
--      soft-deleted), por lo que get_active_period devolvía
--      no_school_year / no_period aunque existiera un periodo
--      con is_active = true.
--   2. Periodos activos con school_year_id NULL o apuntando a
--      otro año (migraciones parciales o inserción directa).
--   3. Varios periodos con is_active = true a la vez.
--   4. classrooms.active_period_id desincronizado.
--   5. get_active_period era ESTRICTO: si el periodo activo no
--      pertenecía al año is_current, no se devolvía nada.
--
-- Solución:
--   A. Recrea (de forma idempotente) todas las columnas y la
--      función auxiliar get_active_school_year_id.
--   B. Sincroniza los DATOS: un solo año is_current, backfill
--      de school_year_id, un solo periodo activo y
--      classrooms.active_period_id alineado.
--   C. get_active_period / get_current_period ahora son
--      RESILIENTES: prefieren el periodo activo del año vigente,
--      pero SIEMPRE caen al periodo activo que ve la directora
--      (is_active = true) y luego al primer periodo abierto.
--   D. activate_period autoasigna el año, mantiene un solo
--      periodo activo y sincroniza las aulas, devolviendo el
--      error REAL si algo falla (en lugar de un mensaje genérico).
--
-- Idempotente: seguro de re-ejecutar.
-- ============================================================

