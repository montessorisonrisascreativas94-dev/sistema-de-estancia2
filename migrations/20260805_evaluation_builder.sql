-- ============================================================
-- 🎓 CONSTRUCTOR DE EVALUACIONES (Evaluation Builder)
-- Estructura jerárquica profesional:
--   Evaluación → Área de Desarrollo → Competencias → Períodos
--   → Módulos → Actividades → (Notas | Observaciones | Evidencias)
